#!/usr/bin/env python3
"""Generate the custom-icon frontends from the AquaClean function SVGs in images/ui/.

The bridge's entities can carry an ``aquaclean:<name>`` icon instead of an ``mdi:`` one (opt-in,
see the component's ``custom_icons`` option). That string is only a label; each frontend that shows
it must know how to draw it. This script writes the Home Assistant frontend:

  frontend/ha-custom-icons.js   Home Assistant custom icon-set (window.customIcons['aquaclean']).
                                Installed by the user via HACS + frontend.extra_module_url.

(The ESP's own web page is handled separately by tools/icons/patch_webserver_v3.py, which injects the
same icons — via iconify_collection() below — into ESPHome's embedded page, keeping web_server
`local: true`.)

Home Assistant's custom-iconset API returns a single filled ``path`` per icon, drawn with
``currentColor``. Our source SVGs use per-path transforms, a fixed slate fill and, for some, a
stroke-only sub-path — none of which that API supports. picosvg normalises each SVG to flattened,
transform-free, fill-only geometry; we then concatenate the resulting path data into one ``d`` and
drop the colour so the frontends theme it.

    python3 tools/icons/generate.py            # write the output
    python3 tools/icons/generate.py --check     # fail if the output is stale (CI)

Needs picosvg (pip).
"""
import argparse
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UI = ROOT / "images" / "ui"
OUT_HA = ROOT / "frontend" / "ha-custom-icons.js"

PREFIX = "aquaclean"

# The function icons exposed under the aquaclean: prefix, as <icon-name>: <source-file>.
# Icon name = the entity-key stem the firmware sends (e.g. aquaclean:shower). Extend as entities
# adopt more of the ui/ set.
ICONS = {
    "shower": "shower.svg",
    "lady_shower": "lady_shower.svg",
    "spray_intensity": "spray_intensity.svg",
    "lady_spray_intensity": "lady_spray_intensity.svg",
    "seat_heating": "seat_heating.svg",
}

SVG_NS = "http://www.w3.org/2000/svg"


def normalise(src: Path) -> str:
    """Run picosvg and return the merged path data (transforms baked, strokes filled)."""
    out = subprocess.run(["picosvg", str(src)], capture_output=True, text=True, check=True).stdout
    root = ET.fromstring(out)
    ds = [p.get("d", "").strip() for p in root.iter(f"{{{SVG_NS}}}path")]
    ds = [d for d in ds if d]
    if not ds:
        raise SystemExit(f"{src.name}: picosvg produced no path")
    return " ".join(ds)


def entries() -> dict[str, str]:
    """name -> normalised single path `d`, for every icon in ICONS."""
    return {name: normalise(UI / fn) for name, fn in sorted(ICONS.items())}


def build_ha(paths: dict[str, str]) -> str:
    lines = [
        "// GENERATED by tools/icons/generate.py from images/ui/*.svg — do not edit by hand.",
        "// Home Assistant custom icon-set for the Geberit AquaClean bridge.",
        "// Install: see docs/custom-icons.md (copy to config/www/geberit-aquaclean-icons/ and add it under",
        "// frontend.extra_module_url). Registers the 'aquaclean' set on both the current (customIcons)",
        "// and legacy (customIconsets) Home Assistant frontend APIs.",
        "(function () {",
        '  "use strict";',
        "  const V = \"0 0 24 24\";",
        "  const ICONS = {",
    ]
    for name, d in paths.items():
        lines.append(f'    {name!r}: {d!r},')
    lines += [
        "  };",
        "  const getIcon = async function (name) {",
        "    const path = ICONS[name];",
        "    return path ? { path, viewBox: V } : undefined;",
        "  };",
        "  const getIconList = async function () {",
        "    return Object.keys(ICONS).map(function (name) { return { name: name }; });",
        "  };",
        "  // Register both the legacy (customIconsets) and the current (customIcons) frontend APIs,",
        "  // so the icons resolve regardless of the Home Assistant frontend version.",
        "  window.customIconsets = window.customIconsets || {};",
        f'  window.customIconsets[{PREFIX!r}] = getIcon;',
        "  window.customIcons = window.customIcons || {};",
        f'  window.customIcons[{PREFIX!r}] = {{ getIcon: getIcon, getIconList: getIconList }};',
        "})();",
        "",
    ]
    return "\n".join(lines)


def iconify_collection(paths: dict[str, str]) -> dict:
    """The aquaclean icons as an Iconify collection (for window.IconifyPreload).

    Shared with tools/icons/patch_webserver_v3.py, which injects this into ESPHome's embedded v3
    web page so the device's own page renders the icons while keeping web_server `local: true`.
    """
    return {
        "prefix": PREFIX,
        "width": 24,
        "height": 24,
        "icons": {name: {"body": f'<path d="{d}" fill="currentColor"/>'} for name, d in paths.items()},
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the output is stale")
    args = ap.parse_args()
    content = build_ha(entries())
    if args.check:
        current = OUT_HA.read_text(encoding="utf-8") if OUT_HA.exists() else ""
        if current != content:
            print(f"STALE: {OUT_HA.relative_to(ROOT)} — run tools/icons/generate.py", file=sys.stderr)
            return 1
        print("ha-custom-icons.js up to date")
        return 0
    OUT_HA.parent.mkdir(parents=True, exist_ok=True)
    OUT_HA.write_text(content, encoding="utf-8")
    print(f"wrote {OUT_HA.relative_to(ROOT)} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
